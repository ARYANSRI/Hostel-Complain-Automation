@app.post("/save-gemini-key")
async def save_gemini_key(req: ApiKeyRequest):
    key = req.api_key.strip()
    os.environ["GEMINI_API_KEY"] = key
    try:
        env_content = ""
        if os.path.exists(".env"):
            with open(".env", "r", encoding="utf-8") as f:
                env_content = f.read()
        if "GEMINI_API_KEY=" in env_content:
            env_content = re.sub(r"GEMINI_API_KEY=.*", f"GEMINI_API_KEY={key}", env_content)
        else:
            env_content += f"\nGEMINI_API_KEY={key}\n"
        with open(".env", "w", encoding="utf-8") as f:
            f.write(env_content.strip() + "\n")
    except Exception as e:
        logger.warning(f"Could not save key to .env file: {e}")
    return {"success": True, "message": "API key configured successfully"}

@app.post("/analyze-image")
async def analyze_image_endpoint(req: ImageAnalysisRequest):
    """
    Accepts a base64 encoded image and returns a concise problem description generated by Gemini AI.
    """
    load_dotenv(override=True)
    logger.info("Received image analysis request...")
    try:
        raw_image_data = req.image
        if not raw_image_data:
            return {"success": False, "error": "No image data provided."}

        mime_type = req.mime_type or "image/jpeg"
        # If it's a data URL like "data:image/png;base64,iVBORw..."
        if "base64," in raw_image_data:
            header, base64_str = raw_image_data.split("base64,", 1)
            mime_match = re.search(r"data:([^;]+);", header)
            if mime_match:
                mime_type = mime_match.group(1)
        else:
            base64_str = raw_image_data

        image_bytes = base64.b64decode(base64_str)
        result = describe_image_issue(
            image_bytes=image_bytes, 
            mime_type=mime_type, 
            api_key=req.api_key,
            file_name=req.file_name
        )
        return result
    except Exception as e:
        logger.error(f"Error analyzing image: {e}")
        return {"success": False, "error": f"Failed to analyze image: {str(e)}"}

